//! Key actions and their help descriptions.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Action {
    InputChar(char),
    Submit,
    Newline,
    Escape,
    Quit,
    CtrlC,
    CtrlD,
    Backspace,
    Delete,
    MoveLeft,
    MoveRight,
    WordLeft,
    WordRight,
    LineStart,
    LineEnd,
    DeleteWord,
    KillToStart,
    KillToEnd,
    Yank,
    TabComplete,
    HistoryUp,
    HistoryDown,
    HistorySearch,
    QueueBack,
    ScrollUp,
    ScrollDown,
    ScrollTop,
    ScrollBottom,
    Help,
    Palette,
    Models,
    CycleMode,
    CycleModel,
    ToggleThinking,
    ToggleToolOutput,
}

impl Action {
    /// Canonical name used by `settings.json` key overrides and notices.
    pub fn name(self) -> &'static str {
        match self {
            Action::InputChar(_) => "input",
            Action::Submit => "submit",
            Action::Newline => "newline",
            Action::Escape => "escape",
            Action::Quit => "quit",
            Action::CtrlC => "interrupt",
            Action::CtrlD => "quit_empty",
            Action::Backspace => "backspace",
            Action::Delete => "delete",
            Action::MoveLeft => "left",
            Action::MoveRight => "right",
            Action::WordLeft => "word_left",
            Action::WordRight => "word_right",
            Action::LineStart => "line_start",
            Action::LineEnd => "line_end",
            Action::DeleteWord => "delete_word",
            Action::KillToStart => "kill_to_start",
            Action::KillToEnd => "kill_to_end",
            Action::Yank => "yank",
            Action::TabComplete => "complete",
            Action::HistoryUp => "history_up",
            Action::HistoryDown => "history_down",
            Action::HistorySearch => "history",
            Action::QueueBack => "queue_back",
            Action::ScrollUp => "scroll_up",
            Action::ScrollDown => "scroll_down",
            Action::ScrollTop => "scroll_top",
            Action::ScrollBottom => "scroll_bottom",
            Action::Help => "help",
            Action::Palette => "palette",
            Action::Models => "models",
            Action::CycleMode => "cycle_mode",
            Action::CycleModel => "cycle_model",
            Action::ToggleThinking => "thinking",
            Action::ToggleToolOutput => "tool_output",
        }
    }

    /// Parse a name from `settings.json`. `None` means unknown.
    pub fn from_name(name: &str) -> Option<Action> {
        let key = name.trim().to_ascii_lowercase().replace('-', "_");
        Some(match key.as_str() {
            "input" => Action::InputChar(' '),
            "submit" | "send" => Action::Submit,
            "newline" => Action::Newline,
            "escape" | "esc" => Action::Escape,
            "quit" | "exit" => Action::Quit,
            "interrupt" | "ctrl_c" => Action::CtrlC,
            "quit_empty" | "ctrl_d" => Action::CtrlD,
            "backspace" => Action::Backspace,
            "delete" | "del" => Action::Delete,
            "left" | "move_left" => Action::MoveLeft,
            "right" | "move_right" => Action::MoveRight,
            "word_left" => Action::WordLeft,
            "word_right" => Action::WordRight,
            "line_start" | "home" => Action::LineStart,
            "line_end" | "end" => Action::LineEnd,
            "delete_word" => Action::DeleteWord,
            "kill_to_start" => Action::KillToStart,
            "kill_to_end" => Action::KillToEnd,
            "yank" => Action::Yank,
            "complete" | "tab" => Action::TabComplete,
            "history_up" => Action::HistoryUp,
            "history_down" => Action::HistoryDown,
            "history" | "history_search" => Action::HistorySearch,
            "queue_back" | "take_queued" => Action::QueueBack,
            "scroll_up" => Action::ScrollUp,
            "scroll_down" => Action::ScrollDown,
            "scroll_top" | "top" => Action::ScrollTop,
            "scroll_bottom" | "bottom" => Action::ScrollBottom,
            "help" => Action::Help,
            "palette" => Action::Palette,
            "models" => Action::Models,
            "cycle_mode" | "mode" => Action::CycleMode,
            "cycle_model" | "model" => Action::CycleModel,
            "thinking" | "toggle_thinking" => Action::ToggleThinking,
            "tool_output" | "toggle_tool_output" => Action::ToggleToolOutput,
            _ => return None,
        })
    }

    /// Very short label for the two-column help layout.
    pub fn short(self) -> &'static str {
        match self {
            Action::InputChar(_) => "type",
            Action::Submit => "send",
            Action::Newline => "newline",
            Action::Escape => "close / abort",
            Action::Quit => "quit",
            Action::CtrlC => "interrupt",
            Action::CtrlD => "quit",
            Action::Backspace => "backspace",
            Action::Delete => "delete",
            Action::MoveLeft => "left",
            Action::MoveRight => "right",
            Action::WordLeft => "word left",
            Action::WordRight => "word right",
            Action::LineStart => "line start",
            Action::LineEnd => "line end",
            Action::DeleteWord => "delete word",
            Action::KillToStart => "kill to start",
            Action::KillToEnd => "kill to end",
            Action::Yank => "yank",
            Action::TabComplete => "complete",
            Action::HistoryUp => "older prompt",
            Action::HistoryDown => "newer prompt",
            Action::HistorySearch => "history",
            Action::QueueBack => "take queued",
            Action::ScrollUp => "scroll up",
            Action::ScrollDown => "scroll down",
            Action::ScrollTop => "top",
            Action::ScrollBottom => "bottom",
            Action::Help => "this help",
            Action::Palette => "palette",
            Action::Models => "models",
            Action::CycleMode => "cycle mode",
            Action::CycleModel => "cycle model",
            Action::ToggleThinking => "thinking",
            Action::ToggleToolOutput => "tool output",
        }
    }

    /// Description shown in the help dialog, generated from the key map.
    pub fn label(self) -> &'static str {
        match self {
            Action::InputChar(_) => "type",
            Action::Submit => "send, or queue while running",
            Action::Newline => "newline",
            Action::Escape => "close dialog / abort run / clear",
            Action::Quit => "quit",
            Action::CtrlC => "interrupt, clear, or quit twice",
            Action::CtrlD => "quit on empty input",
            Action::Backspace => "delete one character",
            Action::Delete => "delete forward",
            Action::MoveLeft => "move left",
            Action::MoveRight => "move right",
            Action::WordLeft => "word left",
            Action::WordRight => "word right",
            Action::LineStart => "start of line",
            Action::LineEnd => "end of line",
            Action::DeleteWord => "delete word",
            Action::KillToStart => "delete to start",
            Action::KillToEnd => "delete to end",
            Action::Yank => "paste the last deleted text",
            Action::TabComplete => "complete command",
            Action::HistoryUp => "older prompt",
            Action::HistoryDown => "newer prompt",
            Action::HistorySearch => "search the prompt history",
            Action::QueueBack => "take the last queued prompt back",
            Action::ScrollUp => "scroll up",
            Action::ScrollDown => "scroll down",
            Action::ScrollTop => "top of transcript",
            Action::ScrollBottom => "bottom of transcript",
            Action::Help => "shortcuts",
            Action::Palette => "command palette",
            Action::Models => "model picker",
            Action::CycleMode => "cycle mode",
            Action::CycleModel => "cycle recent model",
            Action::ToggleThinking => "show or hide thinking",
            Action::ToggleToolOutput => "expand or collapse tools",
        }
    }
}
